namespace Vecerdi.Extensions.DependencyInjection.Analyzers.Tests;

using static GeneratorHarness;

[TestClass]
public sealed class DependencyInjectionSourceGeneratorTests {
    private const string Usings = /*lang=csharp*/
        """
        using System;
        using System.Collections.Generic;
        using Vecerdi.Extensions.DependencyInjection;
        using Vecerdi.Extensions.DependencyInjection.Infrastructure;

        """;

    private static string Normalize(string text) => text.Replace("\r\n", "\n");

    private static void AssertContains(string generated, params string[] lines) {
        foreach (var line in lines) {
            Assert.Contains(line, generated, $"Missing from the generated source:\n{line}\n\nGenerated:\n{generated}");
        }
    }

    [TestMethod]
    public void GeneratesTheWholeContext() {
        var run = RunAndCompile(Usings + """
            namespace Game;

            public interface IScore { }

            public sealed class Hud : BaseMonoBehaviour {
                [Inject] public IScore Score { get; set; } = null!;
            }

            public sealed class Splash : BaseMonoBehaviour { }

            public partial class GameInjectors : TypeInjectorResolverContext { }
            """);

        const string expected = """
            // <auto-generated/>
            #nullable enable
            using System;
            using System.Linq;
            using Microsoft.Extensions.DependencyInjection;
            using Vecerdi.Extensions.DependencyInjection;
            using Vecerdi.Extensions.DependencyInjection.Infrastructure;
            namespace Game
            {
                public partial class GameInjectors
                {
                    public override ITypeInjector? GetTypeInjector(Type type)
                    {
                        return type.FullName switch
                        {
                            "Game.Hud" => HudInjector.Instance,
                            "Game.Splash" => NoOpInjector.Instance,
                            _ => null
                        };
                    }

                    private sealed class NoOpInjector : ITypeInjector
                    {
                        public static readonly NoOpInjector Instance = new();
                        public void Inject(IServiceProvider serviceProvider, object instance) { }
                    }

                    private sealed class HudInjector : ITypeInjector
                    {
                        public static readonly HudInjector Instance = new();
                        public void Inject(IServiceProvider serviceProvider, object instance)
                        {
                            var typedInstance = (global::Game.Hud)instance;
                            typedInstance.Score = serviceProvider.GetRequiredService<global::Game.IScore>();
                        }
                    }
                }
            }

            """;
        Assert.AreEqual(Normalize(expected), Normalize(run.GeneratedOrFail));
        Assert.IsEmpty(run.GeneratorDiagnostics);
    }

    [TestMethod]
    public void RequiredAndOptional_PickGetRequiredServiceOrGetService() {
        var run = RunAndCompile(Usings + """
            public interface IA { }
            public sealed class Card : BaseMonoBehaviour {
                [Inject] public IA Required { get; set; } = null!;
                [Inject(isRequired: false)] public IA? Optional { get; set; }
            }
            public partial class Context : TypeInjectorResolverContext { }
            """);

        AssertContains(run.GeneratedOrFail,
            "typedInstance.Required = serviceProvider.GetRequiredService<global::IA>();",
            "typedInstance.Optional = serviceProvider.GetService<global::IA>();");
    }

    [TestMethod]
    public void KeyedServices_PassTheKeyLiteral() {
        var run = RunAndCompile(Usings + """
            public interface IA { }
            public sealed class Card : BaseMonoBehaviour {
                [InjectFromKeyedServices("primary")] public IA ByString { get; set; } = null!;
                [InjectFromKeyedServices(42, isRequired: false)] public IA? ByInt { get; set; }
                [InjectFromKeyedServices("say \"hi\"")] public IA Quoted { get; set; } = null!;
            }
            public partial class Context : TypeInjectorResolverContext { }
            """);

        AssertContains(run.GeneratedOrFail,
            "typedInstance.ByString = serviceProvider.GetRequiredKeyedService<global::IA>(\"primary\");",
            "typedInstance.ByInt = serviceProvider.GetKeyedService<global::IA>(42);",
            "typedInstance.Quoted = serviceProvider.GetRequiredKeyedService<global::IA>(\"say \\\"hi\\\"\");");
    }

    [TestMethod]
    public void ServiceProviderProperty_GetsTheProviderItself() {
        var run = RunAndCompile(Usings + """
            public sealed class Card : BaseMonoBehaviour {
                [Inject] public IServiceProvider Services { get; set; } = null!;
            }
            public partial class Context : TypeInjectorResolverContext { }
            """);

        AssertContains(run.GeneratedOrFail, "typedInstance.Services = serviceProvider;");
        Assert.IsEmpty(run.GeneratorDiagnostics);
    }

    [TestMethod]
    public void KeyedServiceProvider_WarnsAndIgnoresTheKey() {
        var run = RunAndCompile(Usings + """
            public sealed class Card : BaseMonoBehaviour {
                [InjectFromKeyedServices("ignored")] public IServiceProvider Services { get; set; } = null!;
            }
            public partial class Context : TypeInjectorResolverContext { }
            """);

        AssertContains(run.GeneratedOrFail, "typedInstance.Services = serviceProvider;");
        CollectionAssert.AreEqual(new[] { "VDI0007" }, run.GeneratorDiagnosticIds.ToArray());
    }

    [TestMethod]
    public void Collections_ResolveAllServicesAndMaterialize() {
        var run = RunAndCompile(Usings + """
            public interface IA { }
            public sealed class Card : BaseMonoBehaviour {
                [Inject] public IEnumerable<IA> Enumerable { get; set; } = null!;
                [Inject] public IA[] Array { get; set; } = null!;
                [Inject] public IReadOnlyList<IA> ReadOnlyList { get; set; } = null!;
                [Inject] public IReadOnlyCollection<IA> ReadOnlyCollection { get; set; } = null!;
                [Inject] public List<IA> List { get; set; } = null!;
                [Inject] public IList<IA> IList { get; set; } = null!;
                [Inject] public ICollection<IA> Collection { get; set; } = null!;
                [InjectFromKeyedServices("k")] public List<IA> Keyed { get; set; } = null!;
            }
            public partial class Context : TypeInjectorResolverContext { }
            """);

        AssertContains(run.GeneratedOrFail,
            "typedInstance.Enumerable = serviceProvider.GetServices<global::IA>();",
            "typedInstance.Array = serviceProvider.GetServices<global::IA>().ToArray();",
            "typedInstance.ReadOnlyList = serviceProvider.GetServices<global::IA>().ToArray();",
            "typedInstance.ReadOnlyCollection = serviceProvider.GetServices<global::IA>().ToArray();",
            "typedInstance.List = serviceProvider.GetServices<global::IA>().ToList();",
            "typedInstance.IList = serviceProvider.GetServices<global::IA>().ToList();",
            "typedInstance.Collection = serviceProvider.GetServices<global::IA>().ToList();",
            "typedInstance.Keyed = serviceProvider.GetKeyedServices<global::IA>(\"k\").ToList();");
    }

    [TestMethod]
    public void InheritedProperties_AreInjectedThroughTheDerivedType_AndAbstractBasesGetNoEntry() {
        var run = RunAndCompile(Usings + """
            public interface IA { }
            public interface IB { }
            public abstract class CardBase : BaseMonoBehaviour {
                [Inject] public IA FromBase { get; set; } = null!;
            }
            public sealed class Card : CardBase {
                [Inject] public IB Own { get; set; } = null!;
            }
            public partial class Context : TypeInjectorResolverContext { }
            """);

        var generated = run.GeneratedOrFail;
        AssertContains(generated,
            "\"Card\" => CardInjector.Instance,",
            "typedInstance.Own = serviceProvider.GetRequiredService<global::IB>();",
            "typedInstance.FromBase = serviceProvider.GetRequiredService<global::IA>();");
        Assert.DoesNotContain("CardBase", generated);
    }

    [TestMethod]
    public void PartialClassAcrossParts_GetsOneInjector() {
        var run = RunAndCompile(Usings + """
            public interface IA { }
            public interface IB { }
            public sealed partial class Card : BaseMonoBehaviour {
                [Inject] public IA First { get; set; } = null!;
            }
            public sealed partial class Card {
                [Inject] public IB Second { get; set; } = null!;
            }
            public partial class Context : TypeInjectorResolverContext { }
            """);

        var generated = run.GeneratedOrFail;
        Assert.AreEqual(1, generated.Split("private sealed class CardInjector").Length - 1);
        AssertContains(generated,
            "typedInstance.First = serviceProvider.GetRequiredService<global::IA>();",
            "typedInstance.Second = serviceProvider.GetRequiredService<global::IB>();");
    }

    [TestMethod]
    public void Eligibility_FollowsMonoBehaviourBaseMonoBehaviourAndExclusion() {
        var run = RunAndCompile(Usings + """
            public interface IA { }
            public sealed class PlainWithoutInjection : UnityEngine.MonoBehaviour { }
            public sealed class PlainWithInjection : UnityEngine.MonoBehaviour {
                [Inject] public IA Service { get; set; } = null!;
            }
            public sealed class BaseWithoutInjection : BaseMonoBehaviour { }
            [ExcludeFromInjectionGeneration]
            public sealed class OptedOut : BaseMonoBehaviour {
                [Inject] public IA Service { get; set; } = null!;
            }
            public sealed class NotAMonoBehaviour {
                [Inject] public IA Service { get; set; } = null!;
            }
            public partial class Context : TypeInjectorResolverContext { }
            """);

        var generated = run.GeneratedOrFail;
        AssertContains(generated,
            "\"PlainWithInjection\" => PlainWithInjectionInjector.Instance,",
            "\"BaseWithoutInjection\" => NoOpInjector.Instance,");
        Assert.DoesNotContain("PlainWithoutInjection", generated);
        Assert.DoesNotContain("OptedOut", generated);
        Assert.DoesNotContain("NotAMonoBehaviour", generated);
    }

    [TestMethod]
    public void SameNameInDifferentNamespaces_GetsDistinctInjectorNames() {
        var run = RunAndCompile(Usings + """
            public interface IA { }
            namespace One { public sealed class Card : Vecerdi.Extensions.DependencyInjection.BaseMonoBehaviour { [Vecerdi.Extensions.DependencyInjection.Inject] public global::IA Service { get; set; } = null!; } }
            namespace Two { public sealed class Card : Vecerdi.Extensions.DependencyInjection.BaseMonoBehaviour { [Vecerdi.Extensions.DependencyInjection.Inject] public global::IA Service { get; set; } = null!; } }
            public partial class Context : TypeInjectorResolverContext { }
            """);

        AssertContains(run.GeneratedOrFail,
            "\"One.Card\" => CardInjector.Instance,",
            "\"Two.Card\" => Card1Injector.Instance,",
            "var typedInstance = (global::Two.Card)instance;");
    }

    [TestMethod]
    public void NestedType_IsKeyedByItsRuntimeFullName() {
        // Type.FullName joins nested types with '+', so that is what the switch must match.
        var run = RunAndCompile(Usings + """
            namespace Game;
            public interface IA { }
            public static class Screens {
                public sealed class Card : BaseMonoBehaviour {
                    [Inject] public IA Service { get; set; } = null!;
                }
            }
            public partial class Context : TypeInjectorResolverContext { }
            """);

        AssertContains(run.GeneratedOrFail,
            "\"Game.Screens+Card\" => CardInjector.Instance,",
            "var typedInstance = (global::Game.Screens.Card)instance;");
    }

    [TestMethod]
    public void ContextInTheGlobalNamespace_KeepsItsModifiers() {
        var run = RunAndCompile(Usings + """
            public sealed class Card : BaseMonoBehaviour { }
            internal sealed partial class Context : TypeInjectorResolverContext { }
            """);

        var generated = run.GeneratedOrFail;
        AssertContains(generated, "internal sealed partial class Context");
        Assert.DoesNotContain("namespace", generated);
    }

    [TestMethod]
    public void NoEligibleTypes_ReturnsNullAndReportsIt() {
        var run = RunAndCompile(Usings + """
            public partial class Context : TypeInjectorResolverContext { }
            """);

        AssertContains(run.GeneratedOrFail, "return null; // No eligible types found for context 'Context'.");
        CollectionAssert.AreEqual(new[] { "VDI0004" }, run.GeneratorDiagnosticIds.ToArray());
    }

    [TestMethod]
    public void NoContext_GeneratesNothing() {
        var run = RunAndCompile(Usings + """
            public sealed class Card : BaseMonoBehaviour { }
            """);

        Assert.IsNull(run.Generated);
        Assert.IsEmpty(run.GeneratorDiagnostics);
    }

    [TestMethod]
    public void GenericContext_IsReportedAndSkipped() {
        var run = Run(Usings + """
            public sealed class Card : BaseMonoBehaviour { }
            public partial class Context<T> : TypeInjectorResolverContext { }
            """);

        Assert.IsNull(run.Generated);
        CollectionAssert.AreEqual(new[] { "VDI0002" }, run.GeneratorDiagnosticIds.ToArray());
    }

    [TestMethod]
    public void MultipleContexts_AreReported() {
        var run = Run(Usings + """
            public sealed class Card : BaseMonoBehaviour { }
            public partial class First : TypeInjectorResolverContext { }
            public partial class Second : TypeInjectorResolverContext { }
            """);

        CollectionAssert.AreEqual(new[] { "VDI0003", "VDI0003" }, run.GeneratorDiagnosticIds.ToArray());
    }

    [TestMethod]
    public void InvalidProperties_AreReportedAndSkipped() {
        var run = RunAndCompile(Usings + """
            public interface IA { }
            public sealed class Card : BaseMonoBehaviour {
                [Inject, InjectFromKeyedServices("k")] public IA Twice { get; set; } = null!;
                [Inject] public IA PrivateSetter { get; private set; } = null!;
                [Inject] public IA InitOnly { get; init; } = null!;
                [Inject] public IA Valid { get; set; } = null!;
            }
            public partial class Context : TypeInjectorResolverContext { }
            """);

        var generated = run.GeneratedOrFail;
        AssertContains(generated, "typedInstance.Valid = serviceProvider.GetRequiredService<global::IA>();");
        Assert.DoesNotContain("typedInstance.Twice", generated);
        Assert.DoesNotContain("typedInstance.PrivateSetter", generated);
        Assert.DoesNotContain("typedInstance.InitOnly", generated);
        CollectionAssert.AreEquivalent(new[] { "VDI0006", "VDI0005", "VDI0001" }, run.GeneratorDiagnosticIds.ToArray());
    }
}
